-- Database Schema for CAP-12 Warehouse Management
DROP TABLE IF EXISTS ROUTE_RESULTS;
DROP TABLE IF EXISTS SLOT_RECOMMENDATIONS;
DROP TABLE IF EXISTS REPLENISHMENT_ALERTS;
DROP TABLE IF EXISTS ORDER_LINES;
DROP TABLE IF EXISTS INVENTORY;
DROP TABLE IF EXISTS PRODUCTS;
DROP TABLE IF EXISTS WAREHOUSE_LOCATIONS;

CREATE TABLE WAREHOUSE_LOCATIONS (
    LOCATION_ID VARCHAR(20) PRIMARY KEY,
    AISLE VARCHAR(10),
    X INT,
    Y INT,
    CAPACITY INT,
    STATUS VARCHAR(20),
    ALLOWED_CATEGORY VARCHAR(50)
);

CREATE TABLE PRODUCTS (
    SKU_ID VARCHAR(20) PRIMARY KEY,
    PRODUCT_NAME VARCHAR(100),
    CATEGORY VARCHAR(50),
    REQUIRED_CAPACITY INT,
    CURRENT_LOCATION VARCHAR(20)
);

CREATE TABLE INVENTORY (
    SKU_ID VARCHAR(20) PRIMARY KEY,
    CURRENT_STOCK INT,
    MINIMUM_STOCK INT
);

CREATE TABLE ORDER_LINES (
    ORDER_LINE_ID VARCHAR(20) PRIMARY KEY,
    ORDER_ID VARCHAR(20),
    ORDER_DATE VARCHAR(20),
    SKU_ID VARCHAR(20),
    QUANTITY INT
);

CREATE TABLE SLOT_RECOMMENDATIONS (
    RECOMMENDATION_ID VARCHAR(20) PRIMARY KEY,
    SKU_ID VARCHAR(20),
    PRODUCT_NAME VARCHAR(100),
    DEMAND_CLASS VARCHAR(20),
    CURRENT_LOCATION VARCHAR(20),
    RECOMMENDED_LOCATION VARCHAR(20),
    DISTANCE DOUBLE PRECISION,
    RECOMMENDATION_STATUS VARCHAR(30),
    REASON VARCHAR(500)
);

CREATE TABLE ROUTE_RESULTS (
    ORDER_ID VARCHAR(20) PRIMARY KEY,
    BASELINE_ROUTE_SEQUENCE VARCHAR(1000),
    OPTIMIZED_ROUTE_SEQUENCE VARCHAR(1000),
    BASELINE_DISTANCE DOUBLE PRECISION,
    OPTIMIZED_DISTANCE DOUBLE PRECISION,
    DISTANCE_SAVED DOUBLE PRECISION,
    PCT_DISTANCE_REDUCTION DOUBLE PRECISION,
    BASELINE_TIME_SEC DOUBLE PRECISION,
    OPTIMIZED_TIME_SEC DOUBLE PRECISION,
    TIME_SAVED_SEC DOUBLE PRECISION,
    ROUTE_STATUS VARCHAR(20),
    NOTES VARCHAR(500)
);

CREATE TABLE REPLENISHMENT_ALERTS (
    SKU_ID VARCHAR(20) PRIMARY KEY,
    PRODUCT_NAME VARCHAR(100),
    CURRENT_STOCK INT,
    MINIMUM_STOCK INT,
    STOCK_STATUS VARCHAR(30),
    REPLENISHMENT_REQUIRED VARCHAR(10)
);
