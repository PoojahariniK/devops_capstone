-- Query 1: Executive KPI Overview
SELECT
    TOTAL_ORDERS,
    AVG_BASELINE_DISTANCE,
    AVG_OPTIMIZED_DISTANCE,
    TOTAL_DISTANCE_SAVED,
    AVG_PCT_DISTANCE_REDUCTION,
    AVG_BASELINE_TIME_SEC,
    AVG_OPTIMIZED_TIME_SEC,
    TOTAL_TIME_SAVED_SEC,
    ORDERS_IMPROVED,
    ORDERS_WORSE,
    ORDERS_IDENTICAL
FROM VW_PERFORMANCE_ANALYTICS;

-- Query 2: Order-Level Pick Route Comparison Table
SELECT
    ORDER_ID,
    BASELINE_DISTANCE,
    OPTIMIZED_DISTANCE,
    DISTANCE_SAVED,
    PCT_DISTANCE_REDUCTION,
    BASELINE_TIME_SEC,
    OPTIMIZED_TIME_SEC,
    TIME_SAVED_SEC,
    ROUTE_STATUS,
    NOTES
FROM ROUTE_RESULTS
ORDER BY ORDER_ID;

-- Query 3: Demand Segmentation & Product Inventory Status
SELECT
    D.SKU_ID,
    D.PRODUCT_NAME,
    D.CATEGORY,
    D.ORDER_FREQUENCY,
    D.TOTAL_QUANTITY,
    D.DEMAND_CLASS,
    P.CURRENT_LOCATION,
    P.REQUIRED_CAPACITY,
    I.CURRENT_STOCK,
    I.MINIMUM_STOCK,
    CASE WHEN I.CURRENT_STOCK <= I.MINIMUM_STOCK THEN 'ALERT' ELSE 'HEALTHY' END AS STOCK_HEALTH
FROM (
    SELECT
        P.SKU_ID,
        P.PRODUCT_NAME,
        P.CATEGORY,
        COUNT(O.ORDER_LINE_ID) AS ORDER_FREQUENCY,
        COALESCE(SUM(O.QUANTITY), 0) AS TOTAL_QUANTITY,
        CASE
            WHEN COUNT(O.ORDER_LINE_ID) >= 10 THEN 'FAST'
            WHEN COUNT(O.ORDER_LINE_ID) >= 4 THEN 'MEDIUM'
            ELSE 'SLOW'
        END AS DEMAND_CLASS
    FROM PRODUCTS P
    LEFT JOIN ORDER_LINES O ON P.SKU_ID = O.SKU_ID
    GROUP BY P.SKU_ID, P.PRODUCT_NAME, P.CATEGORY
) D
JOIN PRODUCTS P ON D.SKU_ID = P.SKU_ID
JOIN INVENTORY I ON D.SKU_ID = I.SKU_ID
ORDER BY D.ORDER_FREQUENCY DESC;

-- Query 4: Warehouse Spatial Layout & Occupancy
SELECT
    LOCATION_ID,
    AISLE,
    X,
    Y,
    CAPACITY,
    STATUS,
    ALLOWED_CATEGORY,
    SQRT(POWER(X - 0, 2) + POWER(Y - 0, 2)) AS DISTANCE_FROM_DISPATCH
FROM WAREHOUSE_LOCATIONS
ORDER BY AISLE, LOCATION_ID;

-- Query 5: Slot Recommendations & Approval Audit
SELECT
    RECOMMENDATION_ID,
    SKU_ID,
    PRODUCT_NAME,
    DEMAND_CLASS,
    CURRENT_LOCATION,
    RECOMMENDED_LOCATION,
    DISTANCE,
    RECOMMENDATION_STATUS,
    REASON
FROM SLOT_RECOMMENDATIONS
ORDER BY RECOMMENDATION_ID;

-- Query 6: Replenishment Action Priority
SELECT * FROM VW_REPLENISHMENT_PRIORITY;

